import { test, expect, type Page } from '@playwright/test';
const pick = async (p: Page,id: string) => p.locator(`[data-pick="${id}"]`).click();
const connect = async (p: Page,id: string,t: string) => { await pick(p,id); await p.locator(`.d-terminal-picker [data-terminal="${t}"]`).click(); };

test('visible history and shortcuts undo one action across boxes, restore removals, and discard abandoned redo', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror',e => errors.push(e.message));
  await page.goto('/');
  await expect(page.locator('[data-lesson-action="undo"]')).toBeDisabled();
  await page.getByRole('button',{name:'Open switch box',exact:true}).click();
  await expect(page.locator('[data-action="undo"]')).toBeDisabled();
  await pick(page,'feed.hot.switch');
  await expect(page.locator('[data-action="undo"]')).toBeDisabled();
  await page.locator('.d-terminal-picker [data-terminal="switch.a"]').click();
  await connect(page,'load.hot.switch','switch.b');
  await page.locator('[data-action="undo"]').click();
  await expect(page.locator('[data-pick="feed.hot.switch"]')).toContainText('connected');
  await expect(page.locator('[data-pick="load.hot.switch"]')).toContainText('loose');
  await page.keyboard.press('Control+Shift+Z');
  await expect(page.locator('[data-pick="load.hot.switch"]')).toContainText('connected');
  await pick(page,'load.hot.switch'); await page.locator('[data-action="disconnect"]').click();
  await page.keyboard.press('Control+z');
  await expect(page.locator('[data-pick="load.hot.switch"]')).toContainText('connected');
  await page.keyboard.press('Control+y');
  await expect(page.locator('[data-pick="load.hot.switch"]')).toContainText('loose');
  await page.locator('[data-action="close"]').click();
  await page.locator('[data-lesson-action="undo"]').click();
  await expect(page.locator('#hardware-installation [data-end-id="load.hot.switch"]')).toHaveAttribute('data-end-state','connected');
  await page.getByRole('button',{name:'Open fixture box',exact:true}).click();
  await connect(page,'fixture.hot.terminal','light.hot');
  await expect(page.locator('[data-action="redo"]')).toBeDisabled();
  await page.keyboard.press('Control+z');
  await expect(page.locator('[data-pick="fixture.hot.terminal"]')).toContainText('loose');
  await page.keyboard.press('Control+z');
  await page.locator('[data-action="close"]').click();
  await expect(page.locator('#hardware-installation [data-end-id="load.hot.switch"]')).toHaveAttribute('data-end-state','loose');
  await page.keyboard.press('Control+y');
  await expect(page.locator('#hardware-installation [data-end-id="load.hot.switch"]')).toHaveAttribute('data-end-state','connected');
  expect(errors).toEqual([]);
});

test('guided ground splice and separate bonds are real, undoable and stay consistent with the overview', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button',{name:'Open switch box',exact:true}).click();
  await expect(page.locator('.d-ground-guide')).toContainText('not yet created');
  await pick(page,'feed.ground.switch'); await pick(page,'load.ground.switch');
  await page.locator('[data-action="join"]').click();
  await expect(page.locator('.d-box-feedback')).toContainText('Create both grounding pigtails');
  await expect(page.locator('[data-action="undo"]')).toBeDisabled();
  await page.locator('[data-add-pigtail="switch.device-ground"]').click();
  await page.locator('[data-action="undo"]').click();
  await expect(page.locator('[data-pick="switch.device-ground.splice"]')).toHaveCount(0);
  await page.locator('[data-action="redo"]').click();
  await page.locator('[data-add-pigtail="switch.box-ground"]').click();
  await page.locator('[data-action="clear"]').click();
  for (const id of ['feed.ground.switch','load.ground.switch','switch.device-ground.splice','switch.box-ground.splice']) await pick(page,id);
  await page.locator('[data-action="join"]').click();
  await expect(page.locator('.d-ground-indicators')).toContainText('Ground splice complete');
  await connect(page,'switch.device-ground.terminal','switch.ground');
  await connect(page,'switch.box-ground.terminal','switch.box');
  await expect(page.locator('.d-ground-indicators [data-ground-status="complete"]')).toHaveCount(3);
  await page.locator('[data-action="undo"]').click();
  await expect(page.locator('.d-ground-indicators')).toContainText('Steel box not bonded');
  await expect(page.locator('.d-ground-indicators')).toContainText('Switch grounded');
  await page.locator('[data-action="redo"]').click();
  await page.locator('[data-remove-connector="1"]').click();
  await expect(page.locator('.d-ground-indicators [data-ground-status="incomplete"]')).toHaveCount(3);
  await page.locator('[data-action="undo"]').click();
  await expect(page.locator('.d-ground-indicators [data-ground-status="complete"]')).toHaveCount(3);
  await page.locator('[data-action="close"]').click();
  await expect(page.locator('#hardware-installation [data-connector-id="1"]')).toHaveCount(1);
  await page.getByRole('button',{name:'Open fixture box',exact:true}).click();
  await page.locator('[data-action="undo"]').click();
  await expect(page.locator('#hardware-installation [data-end-id="switch.box-ground.terminal"]')).toHaveAttribute('data-end-state','loose');
});
